import { Schema } from 'effect';

export const NODE_TYPES = [
  'person',
  'skill',
  'project',
  'experience',
  'education',
  'organization',
  'domain',
] as const;
export const NodeType = Schema.Literals(NODE_TYPES);
export type NodeType = typeof NodeType.Type;

export const EDGE_TYPES = [
  'uses',
  'at',
  'delivered',
  'led',
  'in-domain',
  'part-of',
  'related-to',
  'taught',
] as const;
export const EdgeType = Schema.Literals(EDGE_TYPES);
export type EdgeType = typeof EdgeType.Type;

/** Which Edge types a source Node Type may declare, and which target types they may point at. ADR 0001. */
export const EDGE_RULES: Record<EdgeType, { from: ReadonlyArray<NodeType>; to: NodeType }> = {
  uses: { from: ['project', 'experience'], to: 'skill' },
  at: { from: ['experience', 'education'], to: 'organization' },
  delivered: { from: ['experience'], to: 'project' },
  led: { from: ['experience'], to: 'project' },
  'in-domain': { from: ['project', 'experience', 'organization'], to: 'domain' },
  'part-of': { from: ['skill'], to: 'skill' },
  'related-to': { from: ['skill'], to: 'skill' },
  taught: { from: ['education'], to: 'skill' },
};

const NODE_ID_RE = new RegExp(`^(${NODE_TYPES.join('|')})/[a-z0-9]+(?:-[a-z0-9]+)*$`);

/** `<type>/<slug>`, matching the file at `content/<type>/<slug>.md`. */
export const NodeId = Schema.String.pipe(
  Schema.check(
    Schema.isPattern(NODE_ID_RE, { description: 'a Node id of the form <type>/<slug>' }),
  ),
);
export type NodeId = typeof NodeId.Type;

export const isNodeId = (s: string): s is NodeId => NODE_ID_RE.test(s);

export const nodeTypeOf = (id: NodeId): NodeType => id.slice(0, id.indexOf('/')) as NodeType;

export const EDGE_ID_SEP = { before: '--', after: '-->' } as const;

/** `<source id>--<edge type>--><target id>`, generated by the indexer. ADR 0003. */
export const edgeId = (source: NodeId, type: EdgeType, target: NodeId): EdgeId =>
  `${source}${EDGE_ID_SEP.before}${type}${EDGE_ID_SEP.after}${target}` as EdgeId;

const SLUG = '[a-z0-9]+(?:-[a-z0-9]+)*';
const EDGE_ID_RE = new RegExp(
  `^((?:${NODE_TYPES.join('|')})/${SLUG})--(${EDGE_TYPES.join('|')})-->((?:${NODE_TYPES.join('|')})/${SLUG})$`,
);

export const EdgeId = Schema.String.pipe(
  Schema.check(
    Schema.isPattern(EDGE_ID_RE, { description: 'an Edge id of the form <src>--<type>--><dst>' }),
  ),
);
export type EdgeId = typeof EdgeId.Type;

export const isEdgeId = (s: string): s is EdgeId => EDGE_ID_RE.test(s);

export const parseEdgeId = (
  id: string,
): { source: NodeId; type: EdgeType; target: NodeId } | undefined => {
  const m = EDGE_ID_RE.exec(id);
  if (!m) return undefined;
  return { source: m[1] as NodeId, type: m[2] as EdgeType, target: m[3] as NodeId };
};

export const GraphId = Schema.Union([NodeId, EdgeId]);
export type GraphId = typeof GraphId.Type;
